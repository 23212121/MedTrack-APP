export const INDIA_STATES = Object.keys(INDIA_STATE_CITIES);

export function citiesForState(state: string): string[] {
  if (!state) return [];
  const exact = INDIA_STATE_CITIES[state];
  const list = exact
    ? exact
    : INDIA_STATE_CITIES[
        INDIA_STATES.find((s) => s.toLowerCase() === state.trim().toLowerCase()) || ""
      ];
  if (!list) return [];
  return [...new Set(list)].sort((a, b) => a.localeCompare(b));
}
